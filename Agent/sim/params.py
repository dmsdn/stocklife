def base_visits_per_member(hh, car) -> float:
    """회원 하나의 이력 기간 총 방문 기대수. 축(가구·차)이 주기를 정한다."""
    cad = VISIT_CADENCE_BASE_DAYS * VISIT_CADENCE_BY_HH.get(hh or 2, 1.05)
    if car:
        cad *= VISIT_CADENCE_CAR_BONUS
    return HISTORY_DAYS / cad


def cycle_days_for_l2(l2: str) -> float:
    """소분류 이름에서 기본 소비주기(일)를 규칙으로 뽑는다. 안 맞으면 기본값."""
    for kw, days in CYCLE_KEYWORDS:
        if kw in l2:
            return float(days)
    return CYCLE_DEFAULT_DAYS
