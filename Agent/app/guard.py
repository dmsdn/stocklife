# ⚠ 규칙은 넷 또는 **다섯** 칸이다(`require` 는 선택). 다섯째가 있으면 그
#   정규식이 발화에 있을 때만 그 규칙을 검사한다.
def _rule_parts(rule):
    """규칙 하나를 `(kind, pattern, allowed, tol, require)` 로 편다."""
    return rule if len(rule) == 5 else (*rule, None)

