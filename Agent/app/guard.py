#
# ㊴ 정규식(regular expression)과 re 모듈
#    "이런 모양의 글자를 찾아라"를 적는 작은 언어. 문자열에서 패턴을 뽑을 때 쓴다.
#      \d      숫자 한 글자          \d+     숫자 하나 이상
#      [\d,]*  숫자나 쉼표가 0개 이상  \s*     공백이 0개 이상
#      ( )     **뽑아낼 부분**을 묶는 괄호(캡처 그룹)
#    re.findall(패턴, 글) → 패턴에 맞는 부분을 **전부** 리스트로 돌려준다.
#      re.findall(r"(\d[\d,]*)\s*원", "우유 2,190원") → ["2,190"]
#    앞의 r"..."은 raw 문자열 — 백슬래시를 그대로 두라는 표시다. 없으면 파이썬이
#    \d를 이스케이프로 해석하려 들어 정규식이 깨진다(정규식엔 항상 r을 붙인다).
#    왜 문자열 검색(in)이 아니라 정규식인가: "2,190원"에서 **숫자만** 떼어내야
#    원장의 2190과 견줄 수 있는데, in 검사로는 떼어낼 수가 없다.
#
# ㊵ 재귀 함수(recursion) — 자기를 다시 부르는 함수
#    원장에 담긴 도구 결과는 dict 안에 list, 그 안에 또 dict가 있는 **깊이를
#    모르는 중첩 구조**다(get_inventory 결과만 봐도 locations 리스트 안에 dict).
#    깊이를 모르니 for를 몇 겹 쓸지 정할 수 없다. 그래서 "값이 dict면 그 값들을
#    같은 함수에 다시 넣고, list면 항목들을 다시 넣고, 숫자면 담는다"로 쓴다.
#    **멈추는 조건이 반드시 있어야 한다** — 여기서는 "숫자·문자열이면 더 안 파고
#    끝낸다"가 그것이다. 없으면 무한히 자기를 불러 프로그램이 죽는다.
#
# ㊶ 값 정규화(normalization) — 견주기 전에 모양을 맞춘다
#    "12,900" 과 12900 은 사람 눈엔 같지만 컴퓨터에겐 문자열과 정수로 아예 다르다.
#    대조하려면 한쪽 모양으로 통일해야 한다: 쉼표를 지우고(.replace) 정수로(int).
#    이 단계를 빼먹으면 **모든 가격이 "근거 없음"으로 걸리는** 가드가 된다 —
#    너무 엄격해서 아무것도 통과 못 하는 검사기는 없는 검사기보다 나쁘다(전부
#    차단되니 결국 꺼버리게 된다).
# ────────────────────────────────────────────────────────────────────────────

