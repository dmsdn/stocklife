    violations = []

    # ── 0단계: **말이 우리 말인가** (08-30 신설, B 제안) ──────────────────────
    # [무엇이 있었나] T17 로컬 모델(Qwen 바탕)이 골든셋에서 두 번 중국어를 냈다.
    #
    #   "지금 주차장 정보를 확인하는 것은 제가职权翻译官: 不能执行此函数…"
    #   "…보통 구강케어용품을 사시는 분은 200일 정도过后，继续翻译"
    #
    #   **SFT 가 안 덮은 자리에서 바탕 모델의 사전지식이 튀어나온다.** 손님에게
    #   그대로 나가면 서비스가 아니다.
    #
    # [왜 데이터가 아니라 가드인가] B 가 D3 에 범위 경계 칸을 넣어 덮으려 하는데,
    #   그건 **덮은 자리에서만** 듣는다. 데이터로 못 덮는 자리는 늘 남고, 그때
    #   나가는 것은 손님 화면이다. **가드는 모델이 무엇이든 마지막에 도는 층**이라
    #   여기 한 겹이 있으면 데이터가 못 덮은 자리도 막힌다.
    #   (Claude 는 이 갈래를 안 내지만, 가드는 발화기를 안 가리는 것이 값어치다.)
    #
    # [왜 「한글이 아니면」이 아닌가] 우리 발화에는 영문·숫자가 정상적으로 섞인다
    #   ("100ml당", "PB-", "A구역"). 막아야 하는 것은 **한자·가나**다.
    #   ⚠ 한자 하나로 막지 않는다 — 상품명에 한자가 섞일 수 있다(産地 표기 따위).
    #     **연속 둘 이상**만 본다. 실측한 누출은 전부 문장 단위였다.
    if re.search(r"[一-鿿぀-ヿ]{2,}", reply):
        hit = re.search(r"[一-鿿぀-ヿ]{2,}", reply).group(0)
        violations.append({"kind": "language", "value": hit, "text": hit,
                           "reason": "non_korean_leak"})
    checked = 0

    for _rule in _FACT_RULES:
        kind, pattern, allowed, tol, require = _rule_parts(_rule)
        # `require` 가 있으면 **그 화제일 때만** 검사한다(08-31 · eta 참조).
        if require and not re.search(require, reply):
            continue
        for match in re.finditer(pattern, reply):
            raw = match.group(1)
            value = _to_int(raw)
            checked += 1
            if kind == "eta":
                clock = _clock_supported(reply[:match.start()], value, ledgers)
                if clock is not None:
                    if not clock:
                        violations.append({"kind": "event_time", "value": value,
                                           "text": raw, "reason": "unsupported"})
                    continue

            # 허용 출처 중 한 곳에라도 근거가 있으면 통과.
            # any(...)는 "하나라도 참인가"(prompts ㉘-b의 all과 짝).
            # tol(허용 오차)만큼 벌려서 본다 — eta는 반올림이 정상이라 3분까지 인정.
            supported = any(
                any(abs(n - value) <= tol for n in nums.get(src, ()))
                for src in allowed
            )
            if supported:
                continue

            # 근거가 없다. 그런데 **웹 원장에는 있는가**가 갈림길이다 —
            # 있으면 "웹을 매장 사실의 출처로 썼다"는 구체적 위반이고,
            # 없으면 그냥 지어낸 것이다. 둘은 원인도 대처도 다르므로 구분해 적는다.
            from_web = any(abs(n - value) <= tol for n in nums.get("web", ()))
            violations.append({
                "kind": kind,
                "value": value,
                "text": raw,
                "reason": "web_only" if from_web else "unsupported",
            })

    # ── 위치: 숫자가 아니라 층·존으로 대조
    seen_loc = _locations(ledgers)
    for floor, zone in _LOC_RE.findall(reply):
        checked += 1
        if not zone:
            # "3층에 있어요"처럼 존 없이 층만 말한 경우 — 층만 맞으면 통과시킨다.
            # 존까지 요구하면 정상 발화가 걸린다(에이전트가 늘 존을 말하진 않는다).
            if any(f == floor for f, _z in seen_loc):
                continue
        elif (floor, zone) in seen_loc:
            continue
        violations.append({"kind": "location", "value": f"{floor}층{zone or ''}",
                           "text": f"{floor}층{zone or ''}", "reason": "unsupported"})

    # ── 2단계: 범주 일관성 — "숫자는 맞는데 의미가 반대"를 잡는다
    facts = _sot_facts(ledgers)
    # 추론 원장에 가용 곡선이 실제로 있나 — 위 replenish_negation 면제가 본다.
    # sot 가 아니라 infer 쪽이라 _sot_facts 밖에서 채운다.
    facts["availability_curve"] = any(
        e.get("tool") == "predict_availability"
        and isinstance(e.get("result"), dict) and e["result"].get("curve")
        for e in ledgers.get("infer", ()))
    for name, applies, pattern, exemptions, why in _CONTRADICTIONS:
        # applies(facts)가 참일 때만 = 원장이 그 판정을 내려둔 경우에만 검사한다.
        # 조건을 안 걸면 원장이 비어 있는 일반 대화까지 이 규칙에 걸린다.
        if not applies(facts):
            continue
        checked += 1
        m = re.search(pattern, reply)  # findall과 달리 **첫 하나**만 찾으면 충분
        if m and exemptions:
            # ── 면제는 **문맥 창**에서 본다 (08-27 개조) ──────────────────────
            # [왜 group(0) 으로는 안 되나] 걸린 구간이 "없어요" 다섯 글자뿐인
            #   규칙에서는 면제 패턴을 아무리 잘 써도 **볼 것이 없다.** 부정을
            #   한정하는 말("매대에는")은 항상 부정어 **앞**에 오기 때문이다.
            #   그래서 앞 24자·뒤 8자를 함께 본다. 한국어는 수식어가 앞에 붙는
            #   구조라 창을 앞으로 길게 잡는다.
            # [창 크기의 근거] 24자면 "지금 1층 D구역 매대에는" 정도가 들어온다.
            #   더 넓히면 앞 문장의 "매대"까지 끌어와 엉뚱한 면제가 생긴다.
            lo, hi = max(0, m.start() - 24), min(len(reply), m.end() + 8)
            window = reply[lo:hi]
            # 면제는 **(창 패턴, 동반 조건)의 목록**이다. 한 규칙에 사유가 여럿일
            # 수 있고 사유마다 조건이 다르기 때문 — replenish_negation 은
            # "시점을 모른다"(조건 없음)와 "구간에 한정"(곡선 필요)이 다르다.
            # 하나로 뭉치면 둘 중 느슨한 쪽이 엄한 쪽의 조건을 무력화한다.
            def _ok(also):
                if also is None:
                    return True
                if callable(also):
                    return bool(also(facts))       # 원장 상태 조건
                return bool(re.search(also, reply))  # 발화 전체에서 찾는 낱말
            # also 를 발화 전체에서 보는 이유: 예비 재고 설명은 부정 뒤에 따로
            # 오는 문장이라 창 안에 없을 수 있다("…없어요. 다만 예비 재고가 …").
            if any(re.search(win, window) and _ok(also) for win, also in exemptions):
                continue
        if m:
            violations.append({
                "kind": "contradiction", "rule": name,
                "value": why, "text": m.group(0),  # group(0) = 실제로 걸린 글자
                "reason": "contradicts_ledger",  # 세 번째 사유 — 아래 주석 참조
            })

    return {"ok": not violations, "violations": violations, "checked": checked}


