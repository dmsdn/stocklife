# [역할] 발화가 사용자에게 나가기 **직전**, 그 안의 매장 사실(가격·재고·위치·시각)이
#   실제로 도구 결과에서 나온 것인지 대조한다. 통과/차단 판정과 사유만 낸다.
#
# [왜 프롬프트로 충분하지 않은가]
#   prompts.py가 "도구 결과에서만 말하라"고 지시하지만 **지시는 보증이 아니다.**
#   LLM은 대부분 지킨다 — 그런데 가격·재고에서 "대부분"은 부족하다.
#   손님이 12,900원이라는 답을 믿고 계산대에 갔는데 13,900원이 찍히면,
#   그 손님에게 이 에이전트는 그날로 쓸모없는 물건이 된다.
#
# [왜 loop.py와 분리하는가]
#   루프는 "대화를 굴리는 일", 가드는 "나가도 되는지 판정하는 일"이다. 섞으면
#   프롬프트 실험(루프)과 안전 기준(가드)의 변경이 git에서 뒤엉켜, 골든셋 점수가
#   떨어졌을 때 무엇 때문인지 분리할 수 없다.
#
# [핵심 규칙 — 출처별 원장 (설계서 §6.6.1)]
#   웹 검색은 **일반 사실의 출처로는 인정**하되(성분 차이·고르는 기준),
#   **매장 사실의 출처로는 인정하지 않는다.**
#   실패 시나리오: LLM이 웹에서 "물티슈 3,900원"을 보고 그대로 말한다. 문장만
#   보면 완벽하고 근거도 있다 — 다만 그건 **다른 가게 가격**이다. 출처를 나눠
#   기록해두지 않으면 이 오류는 영원히 검출되지 않는다.
#
# [안 하는 일 — 경계]
#   · 문장을 고치지 않는다. 다듬기는 재생성(LLM)의 몫이고, 가드가 손대면
#     "누가 쓴 문장인가"가 흐려져 책임 소재가 사라진다.
#   · 차단 후 무엇을 할지도 정하지 않는다(재생성? 안전 문구?) — main.py의 정책.
#   · 일반 상식·인사말은 검사하지 않는다(§6.6.2). 전부 검사하면 못 쓴다.
