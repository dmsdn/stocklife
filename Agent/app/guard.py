def _sot_facts(ledgers: dict) -> dict:
    """sot 원장에서 **판정에 쓸 사실 몇 개**만 뽑아 평평한 dict로 만든다.

    왜 필요한가: 원장은 도구 호출 기록의 리스트라 중첩이 깊다. 모순 규칙이
    매번 그 구조를 헤집으면 규칙 하나 늘 때마다 탐색 코드가 붙는다.
    **"규칙이 보는 면"을 여기서 한 번 평평하게 만들어** 규칙은 dict만 읽게 한다.

    여러 상품을 조회했으면 마지막 것이 남는다 — 발화의 주어가 대개 마지막에
    조회한 상품이기 때문이다(대화의 초점은 앞으로 이동한다).
    """
    facts = {}
    for entry in ledgers.get("sot", ()):
        r = entry.get("result")
        if not isinstance(r, dict):
            continue
        for k in ("pick_qty", "backup_qty", "on_shelf"):
            if k in r:
                facts[k] = r[k]
        # 단종 여부는 get_product 결과 안쪽에 들어 있다
        p = r.get("product")
        if isinstance(p, dict) and p.get("lifecycle_status") == "DISCONTINUED":
            facts["discontinued"] = True
    return facts


# 위치는 숫자 대조가 아니라 **층·구역 문자**로 본다.
# 프롬프트가 "F2-B-R01-B05-L2 → 2층 B구역"으로 바꿔 말하라고 시켰으므로,
# 발화에는 코드가 아니라 사람 말이 나온다. 그 사람 말을 원장의 코드와 견준다.
_LOC_RE = re.compile(r"(\d)\s*층(?:\s*([A-H])\s*구역)?")


def _to_int(s: str) -> int:
    """"12,900" → 12900 (개념 ㊶). 쉼표를 지우고 정수로."""
    return int(s.replace(",", ""))


def _walk_numbers(obj, out):
    """중첩 구조를 끝까지 파고들며 숫자를 전부 모은다 (개념 ㊵ 재귀).

    out은 결과를 담을 set(개념 ⑥)을 **밖에서 받아** 채우는 방식이다.
    함수가 매번 새 set을 만들어 돌려주면 재귀 단계마다 합치는 코드가 더 붙는다.
    """
    if isinstance(obj, bool):
        return                       # True/False는 파이썬에서 1/0으로도 취급된다.
                                     # 안 걸러내면 on_shelf=False가 "0"이라는 근거가 된다.
    if isinstance(obj, (int, float)):
        out.add(int(obj))            # 멈추는 조건 ①: 숫자면 담고 끝
        return
    if isinstance(obj, str):
        # 문자열 안의 숫자도 근거가 된다("2026-08-13 14:20", "500ml", 웹 제목 등).
        # 패턴에 쉼표를 포함시키는 이유(㊶): \d+ 로만 뽑으면 "3,900"이 쉼표에서
        # 끊겨 3과 900이라는 **엉뚱한 두 숫자**가 되고, 정작 3900은 근거 목록에
        # 없게 된다. 그러면 웹에서 온 가격을 "웹에도 없음(=지어냄)"으로 잘못
        # 분류한다 — 차단은 되지만 사유가 틀려서, 프롬프트를 어디부터 고쳐야
        # 할지 알 수 없게 된다. rstrip(",")은 "3,900원"처럼 숫자 뒤에 붙어
        # 딸려온 쉼표를 떼는 것.
        for n in re.findall(r"\d[\d,]*", obj):
            out.add(_to_int(n.rstrip(",")))
        return                       # 멈추는 조건 ②: 문자열은 더 파지 않는다
    if isinstance(obj, dict):
        for v in obj.values():       # dict는 **값들만** 다시 판다(키 이름은 사실이 아니다)
            _walk_numbers(v, out)
        return
    if isinstance(obj, (list, tuple)):
        for v in obj:
            _walk_numbers(v, out)


def _numbers_by_source(ledgers: dict) -> dict:
    """출처 칸별로 "그 칸에서 나온 숫자 집합"을 만든다.

    {"sot": {101042, 12900, 160, ...}, "web": {3900, ...}, ...}
    가드의 판정은 결국 "발화의 이 숫자가 어느 집합에 있나"로 환원된다.
    집합(set)을 쓰는 이유: `n in 집합` 검사가 즉시 끝난다(리스트면 전수 순회).
    """
    out = {}
    for source, entries in ledgers.items():
        acc = set()
        _walk_numbers(entries, acc)
        out[source] = acc
    return out


def _locations(ledgers: dict) -> set:
    """원장에 실제로 등장한 (층, 존문자) 쌍을 모은다.

    location_id는 'F2-B-R01-B05-L2' 꼴이라 앞 두 조각이 층·존이다.
    문자열 전체를 훑어 그 패턴을 찾는 이유: location_id가 결과 dict의 어느
    깊이에 있는지 도구마다 달라서, 구조를 가정하지 않는 편이 안전하다.
    """
    found = set()
    # web 원장은 뺀다 (08-24 검수). 위치는 **매장 사실**이라 웹이 출처가 될 수
    # 없는데(§_FACT_RULES의 원칙 — "web"은 어디에도 없다), repr을 통째로 훑으면
    # 검색 결과 URL·제목에 우연히 "F3-A" 꼴이 실렸을 때 그 층·존이 세탁된다.
    ours = {k: v for k, v in ledgers.items() if k != "web"}
    text = repr(ours)                          # 중첩 구조를 통째로 문자열화
    for floor, zone in re.findall(r"F(\d)-([A-H])", text):
        found.add((floor, zone))
    # ⚠ **층이 정수 필드로만 오는 도구가 있다**(08-28 B 지적).
    #
    #   `get_position` 은 `{"floor_no": 3, "x": …, "y": …}` 를 돌려주고
    #   location_id 문자열을 안 낸다(스냅한 통행 좌표라 매대 id 가 없다).
    #   그래서 위 정규식만으로는 **원장에 층이 있는데도 안 잡혔고**,
    #   에이전트가 `read_as` 가 시킨 대로 "지금 계신 3층…" 이라고 말하면
    #   가드가 `unsupported` 로 막았다.
    #
    #   ⚠ 훈련 데이터 문제가 아니라 **실서비스 결함**이었다 —
    #   `get_position` 의 성공 경로 셋이 전부 층을 말하라고 시키는데
    #   `no_scan_anchor`(층을 안 말한다) 하나만 통과하고 있었다.
    #   궤적이 0건이라 이 충돌이 드러날 자리가 없었다.
    #
    #   존은 `None` 으로 둔다 — **층만 근거가 있고 존은 없다**는 뜻이다.
    #   아래 대조에서 "층만 말한 발화"는 통과하고 "존까지 말한 발화"는
    #   여전히 존 근거를 요구한다. 그게 옳다.
    for floor in re.findall(r"['\"]floor(?:_no|_order)?['\"]\s*:\s*(\d+)", text):
        found.add((floor, None))
    return found


def _recorded_event_times(ledgers: dict) -> set:
    """Read event clock times from SoT only; never treat them as future ETA minutes."""
    found = set()
    def visit(value):
        if isinstance(value, dict):
            raw = value.get("occurred_at_local") or value.get("occurred_at")
            if isinstance(raw, str):
                try:
                    moment = datetime.fromisoformat(raw.replace("Z", "+00:00"))
                    if moment.tzinfo is not None:
                        moment = moment.astimezone(timezone(timedelta(hours=9)))
                    found.add((moment.month, moment.day, moment.hour, moment.minute))
                except ValueError:
                    pass
            for child in value.values():
                visit(child)
        elif isinstance(value, (list, tuple)):
            for child in value:
                visit(child)
    visit(ledgers.get("sot", []))
    return found


def _clock_supported(prefix: str, minute: int, ledgers: dict):
    match = re.search(r"(?:(\d{1,2})\s*월\s*(\d{1,2})\s*일\s*)?"
                      r"(오전|오후|밤|아침|낮|저녁|새벽)?\s*(\d{1,2})\s*시\s*$", prefix)
    if not match:
        return None
    month, day, period, raw_hour = match.groups()
    hour = int(raw_hour)
    if period in ("오후", "저녁", "낮") and hour < 12:
        hour += 12
    elif period == "밤":
        hour = 0 if hour == 12 else hour + 12 if hour < 12 else hour
    elif period in ("오전", "아침", "새벽") and hour == 12:
        hour = 0
    return any(h == hour and m == minute and
               (month is None or (mo == int(month) and d == int(day)))
               for mo, d, h, m in _recorded_event_times(ledgers))


