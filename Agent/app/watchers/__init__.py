# app/watchers/ — 자발형을 깨우는 감시자들의 패키지 (파일명세 §3).
#
# 신호원 셋 + 구동부 + 디스패처:
#   behavior.py  행동 신호(브라우저 → SSE)   — ✅ 08-21 (장면 2: 망설임)
#   world.py     세계 신호(백엔드 → SSE)     — ✅ 08-27 (장면 1: 재고 전환 · 위치 이동)
#   schedule.py  시간 신호(스스로 기상)      — ✅ 08-27 (장면 3: 진입 브리핑 · 재구매)
#   runner.py    **구동부** — SSE 한 줄기를 셋에게 나눠 주고 주기로 배출  ✅ 08-27
#   dispatch.py  개입 하나를 발화까지 — 허가·지시문·루프·가드·전달·기록
#
# ⚠ 신호원 셋은 **서로를 모른다.** 셋을 아는 것은 runner 하나뿐이다 —
#   감시자끼리 서로를 알기 시작하면 그물이 되고, 하나를 고칠 때 셋을 연다.
#
# 공통 규율: 감시자는 **판정까지만** 한다. 말할 권한은 etiquette.py가 발급하고,
# 문장은 loop가 만들고(가드 통과), 전달은 sot_client.push_proactive_message가 한다.
# 이 빈 파일이 폴더를 파이썬 패키지로 만든다(tools/__init__.py와 같은 역할).
