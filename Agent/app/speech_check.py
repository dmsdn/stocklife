# -*- coding: utf-8 -*-
"""**발화의 형식** — 값도 시퀀스도 옳은데 문장이 깨진 것을 잡는다.

[왜 이 파일이 있나 — 08-30]
심판 셋과 가드가 보는 것은 **무엇을 말했나**다. 그런데 **어떻게 말했나**에서
같은 부류의 결함이 08-28 이후 **네 번** 났다.

| | 무엇 | 어떻게 보였나 |
|---|---|---|
| 08-28 | `"98%%"` | 형식 문자열이 그대로 새어 나갔다 |
| 08-28 | `"야끼소바면은(는) 4,090원"` — **2,195건 중 840건(38.3%)** | 말하는 에이전트가 이렇게 말하지 않는다 |
| 08-29 | `"단위가 count_roll 이라"` | **내부 식별자**를 손님에게 읽어 줬다 |
| 08-30 | `"둘러보시다 오시면 **을** 받아보실 수 있어요"` | `josa()` 가 조사만 돌려주는데 **상품명 자리에 그것만** 넣었다 |

⚠ **넷 다 심판 셋을 통과한다.** 숫자는 원장에 있고, 도구도 옳고, 시퀀스도
정상이다. 사각지대 네 축(값·계약·라우팅·표현) 중 **표현**이 이것인데,
`read_as_check`(다섯째 축)는 *결과가 시킨 것*을 보지 *문장이 성한지*는 안 본다.

> **형식은 아무도 안 본다.** 그리고 넷째가 나온 뒤에는 다섯째를 기다리는
> 것이 아니라 **검사기를 만드는 것**이 맞다.

[왜 `Agent/app/` 에 두나] 두 곳이 쓴다 — 평가 러너(발화 채점)와 명세
생성기(궤적을 만들 때). `read_as_check` 와 같은 자리·같은 규약이다.

[정직하게] 이 검사는 **형식만** 본다. 문장이 어색한지·말투가 맞는지는 안
본다(그건 사람과 심판의 몫이다). 여기서 잡는 것은 **사람이 쓰지 않는 꼴**,
즉 코드가 새어 나온 흔적뿐이다.

사용:
    from app.speech_check import defects
    for d in defects(reply):
        print(d["rule"], d["hit"])
"""
from __future__ import annotations

import re

# ── 규칙 — 전부 **실제로 난 결함**에서 왔다 ─────────────────────────────────
# ⚠ 상상으로 패턴을 쓰지 않는다. 08-28 위치 케이스에서 있지도 않은 문형을
#   금지해 **늘 초록인 자**를 만든 적이 있다(트러블슈팅 `재는_자가…` ①).
_RULES = [
    # ① 괄호 조사 — `natural()` 이 못 고른 잔여. "면은(는)" · "것이(가)"
    ("paren_josa", r"[가-힣]\((?:은|는|이|가|을|를|과|와|로|으로|랑|이랑)\)",   # 09-02: 조사 짝만 — '개수(입)' 같은 단위 괄호를 오탐하던 것을 좁혔다
     "괄호 조사가 남았다 — 말하는 에이전트는 '은(는)'이라고 말하지 않는다"),

    # ② 형식 문자열 잔여 — "%s" · "%d" · "98%%"
    #   ⚠ `%` 하나는 정상이다("97.6%"). **둘 연속**과 `%자리표시`만 잡는다.
    #   ⚠ `\b` 를 쓰면 안 된다 — `"%s은"` 처럼 **한글이 바로 붙으면** 파이썬
    #     정규식은 `s` 와 `은` 사이에 경계를 안 둔다(둘 다 단어 문자다).
    #     자체 검산이 이걸 잡았다 — 시험 문장을 실제 결함에서 가져온 값이다.
    ("format_leak", r"%[sdfr]|%%",
     "형식 문자열이 새어 나갔다"),

    # ③ 내부 식별자 — snake_case 나 대문자 상수가 한글 발화에 섞였다.
    #   실제로 난 것: count_roll · tier_role · PICK/BULK · location_id
    ("internal_id",
     r"\b(count_(ea|roll|tab|pair|sheet)|weight_g|volume_ml|length_m|area_m2"
     r"|tier_role|sku_id|l2_code|final_price_krw|price_krw|PICK|BULK)\b",
     "내부 식별자를 손님에게 읽어 줬다 — 종착지는 소비자 화면이다(헌법 7)"),

    # ④ 자리표시가 그대로 — 파이썬 값이 문자열로 굳었다
    ("placeholder", r"\bNone\b|\{\}|\bnan\b|\bNaN\b",
     "값이 없는 자리가 그대로 나갔다"),

    # ⑤ ★ **조사만 남았다** — 낱말이 통째로 빠진 자리 (08-30)
    #   `josa(word, "을")` 은 **조사만** 돌려주는데 상품명 자리에 그것만
    #   넣으면 *"오시면 을 받아보실 수 있어요"* 가 된다.
    #   ⚠ `은|는|을|를` 만 본다 — `이·과·로` 는 홀로 설 수 있다
    #     ("**이** 상품은" · "**과** 자" · "**로** 시작"). 좁게 잡아
    #     거짓 양성을 안 만든다(가드의 정밀도 우선 설계와 같은 판단).
    ("orphan_josa", r"(?:^|(?<=[\s]))([은는을를])(?=[\s.,!?)\"'])",
     "조사만 있고 앞 낱말이 없다 — 이름이 통째로 빠진 문장이다"),

    # ⑥ 매대 코드 그대로 — "F1-H-R08-B03-L2"
    ("location_code", r"\b[BF]?\d?-?[A-Z]-R\d+(-B\d+)?(-L\d+)?\b",
     "매대 코드를 그대로 읽어 줬다 — 손님은 그 코드로 못 찾는다"),
    # ⑦ ★ **sku 번호를 읽어 줬다** (09-04 · 시연에서 실제로 났다)
    #   난 발화 그대로:
    #     "그때 상품 10종을 함께 구매하셨어요(예: sku 210622 3개, 212102 1개,
    #      210420 3개, 208665 2개, 208654 2개)"
    #
    #   ③ internal_id 는 `sku_id` 라는 **토큰**은 잡는데 `sku 210622` 는
    #   안 잡았다. 손님에게 아무 뜻 없는 내부 번호라 성격은 같다(헌법 7).
    #
    #   ⚠ 뿌리는 이 규칙이 아니라 **데이터**였다 — get_purchase_history 가
    #     이름 없이 sku 만 줬다(tools/query.py 의 _with_names 에서 고쳤다).
    #     이 규칙은 **다시 새면 잡는 그물**이지 해결책이 아니다.
    #
    #   [왜 이 세 꼴만 잡나 — 맨숫자를 통째로 금지하지 않는 이유]
    #     가격(134050원) · 연도(2026년) · 전화(01080000001)가 전부 숫자다.
    #     맨 6자리를 다 막으면 멀쩡한 발화가 빨간불이 되고, 그러면 이 검사를
    #     아무도 안 본다(⑤ orphan_josa 와 같은 판단 — 좁게 잡는다).
    #       ⓐ `sku` 라는 낱말이 앞에 붙은 것 — 뜻이 하나뿐이라 안전하다
    #       ⓑ 6자리 뒤에 수량이 붙은 것("212102 1개") — 값이면 「원」이 붙는다
    #       ⓒ 6자리가 쉼표로 나열된 것 — 사람 문장에 이런 나열은 없다
    ("sku_leak",
     r"(?i)\bsku\s*(?:번호|아이디|id)?\s*[:#]?\s*\d{4,}"
     r"|\b\d{6}\s+\d+\s*개"
     r"|\b\d{6}(?:\s*,\s*\d{6})+\b",
     "sku 번호를 손님에게 읽어 줬다 — 상품명으로 말해야 한다(헌법 7)"),
]


def defects(reply: str) -> list[dict]:
    """발화에서 **형식 결함**을 찾는다. 없으면 빈 리스트.

    [반환] `[{"rule": 이름, "hit": 걸린 조각, "why": 사유}, …]`
    """
    out = []
    text = reply or ""
    for name, pattern, why in _RULES:
        m = re.search(pattern, text)
        if m:
            out.append({"rule": name, "hit": m.group(0).strip(), "why": why})
    return out


# ── 소스 린트 — **발화 검사가 원리적으로 못 잡는 자리** ────────────────────
# [왜 발화로는 못 잡나] 조사 일치(`은/는`·`이/가`·`을/를`)는 받침으로 정해지는
#   기계적 규칙인데, **용언 어미가 같은 글자를 쓴다** — "먹**는**"·"갈 것**을**·
#   "가**가**". 발화에서 일반 검사로 만들면 거짓 양성이 쏟아지고, 그러면
#   아무도 안 본다(이 파일의 다른 규칙들과 같은 판단).
#
# [그런데 소스에서는 잡힌다] **서식 자리 바로 뒤에 조사가 하드코딩된** 꼴은
#   문맥이 필요 없다. `"%s는"` 은 `%s` 가 무엇이 되든 절반은 틀린다.
#
#   08-30 실측: 생성기에 그런 자리가 **한 곳** 있었다.
#     "저는 매장 안내를 맡고 있어서 %s는 확인이 안 돼요." % (what, …)
#   재료 여섯이 **전부 받침 없이 끝나서 우연히 맞고 있었다.** 항목 하나만
#   더 넣으면 "영업시간는"이 된다.
#
# ⚠ **안전한 두 꼴은 뺀다** — 안 빼면 28곳이 거짓 양성으로 뜬다:
#     `%s은(는)`  괄호형 — `natural()` 이 받침에 맞춰 하나를 고른다
#     `fill(...)` 안 — `fill` 이 `{p}` 뒤 조사를 이미 고른다
#   `josa(x, "는")` 도 안전하다(그 함수가 고른다).
#   ⚠ 08-30 에 패턴을 두 번 조였다. 처음 판이 5곳을 찍었는데 **넷이 잡음**이었다:
#     `{p}은`     → `fill` 영역이다. `fill` 은 `{p}` 를 쓰고 `%` 서식은 못 쓴다
#                   ⇒ **자리표시 꼴로 갈린다.** `%s`·`%d` 만 본다
#     `%d가지가`  → "가지"는 단위 명사다. 조사가 아니다
#     `%s이에요`  → "이에요"는 계사다. 조사가 아니다
#                   ⇒ 조사 뒤에는 **한글이 안 온다**(공백·구두점·끝).
#                     둘 다 뒤가 한글이라 이 조건으로 빠진다
#
#   > 잡음 넷을 남긴 채로 "5곳 찾았다"고 보고했으면, 받는 쪽은 **네 번
#   > 헛걸음하고 다섯 번째를 안 믿는다.** 자의 값어치는 찾은 수가 아니라
#   > **찾은 것이 전부 진짜인가**에 있다.
_SRC_JOSA = re.compile(r"(%s|%d)(은|는|이|가|을|를|과|와)(?=[\s.,!?)\"']|$)")


def source_lint(path: str, window: int = 3) -> list[dict]:
    """생성기 소스에서 **하드코딩된 조사**를 찾는다.

    [반환] `[{"line": 줄번호, "hit": 걸린 조각, "text": 그 줄}, …]`

    ⚠ `window` 는 앞 몇 줄까지 `fill(`·`josa(` 를 찾을지다. 문자열이 여러 줄에
      걸치므로 그 줄만 봐서는 감싼 함수를 못 본다 — 3줄이면 실측으로 충분하다.
    """
    lines = open(path, encoding="utf-8").read().split("\n")
    out = []
    for i, ln in enumerate(lines):
        if ln.strip().startswith("#"):
            continue                       # 주석 안의 예시는 코드가 아니다
        for m in _SRC_JOSA.finditer(ln):
            ctx = "\n".join(lines[max(0, i - window): i + 1])
            if "fill(" in ctx or "josa(" in ctx:
                continue                   # 조사를 고르는 함수가 감싸고 있다
            out.append({"line": i + 1, "hit": m.group(0), "text": ln.strip()[:76]})
    return out


if __name__ == "__main__":                                   # 자체 검산
    import sys
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:                                        # noqa: BLE001
        pass

    # ⚠ 시험 문장은 **실제로 난 것**과 그 이웃(정상)이다. 정상까지 넣는 이유:
    #   금지 패턴은 잡는 것보다 **안 잡는 것**을 확인해야 쓸 수 있다.
    BAD = [
        ("paren_josa",   "청록원 야끼소바면은(는) 4,090원입니다."),
        ("format_leak",  "1시간 내 보충 확률이 98%%입니다."),
        ("format_leak",  "%s은 3층에 있어요."),
        ("internal_id",  "단위가 count_roll 이라 견줄 수 없어요."),
        ("internal_id",  "tier_role 이 PICK 인 자리에 4개 있어요."),
        ("placeholder",  "가격은 None 원이에요."),
        ("orphan_josa",  "잠시 둘러보시다 오시면 을 받아보실 수 있어요."),
        ("location_code", "F1-H-R08-B03-L2 에 있어요."),
        # 09-04 시연에서 실제로 난 발화 (세 꼴)
        ("sku_leak", "예: sku 210622 3개, 212102 1개, 210420 3개."),
        ("sku_leak", "sku 210622 를 다시 담을까요?"),
        ("sku_leak", "210622, 212102, 210420 을 사셨어요."),
    ]
    OK = [
        "청록원 야끼소바면은 4,090원입니다.",
        "1시간 내 보충 확률이 97.6%입니다.",
        "단위가 롤과 매로 서로 달라 견줄 수 없어요.",
        "이 상품은 3층에 있어요.",                    # '이' 는 홀로 설 수 있다
        "과일은 1층에 있어요.",                       # '과' 로 시작해도 낱말이다
        "1층 H구역 세 번째 랙에 4개 있어요.",
        "물티슈는 여러 종류가 있어요.",
        # ⚠ 08-31 거짓 양성: **따옴표 뒤의 조사는 정상**이다.
        #   앞 구분자로 따옴표·괄호를 허용했더니 이 발화가 걸렸다 —
        #   골든셋이 잡아 줬다. 고아 조사는 **앞이 공백일 때만**이다.
        "'쿡프리즉'은 정확히 없어서 '쿡프리즈' 브랜드로 찾아봤어요.",
        "(캡형)을 찾으시면 3층에 있어요.",
    ]
    bad_ok = 0
    for want, s in BAD:
        got = [d["rule"] for d in defects(s)]
        hit = want in got
        bad_ok += hit
        print(" %-14s %-46s %s" % (want, s[:44], "잡음" if hit else "❌ 못 잡음"))
    print()
    ok_ok = 0
    for s in OK:
        d = defects(s)
        ok_ok += not d
        print(" %-46s %s" % (s[:44], "통과" if not d else "❌ 거짓양성 " + str(d)))
    print("\n=> 결함 %d/%d 검출 · 정상 %d/%d 통과" % (bad_ok, len(BAD), ok_ok, len(OK)))
    assert bad_ok == len(BAD) and ok_ok == len(OK), "자체 검산 실패"
    print("speech_check 자체 검산 통과")
