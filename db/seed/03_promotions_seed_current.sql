SELECT COUNT(*) AS promotion_rows FROM promotions;

SELECT COUNT(*) AS active_promotions
FROM promotions
WHERE '2026-08-18 12:00:00' BETWEEN starts_at AND ends_at;

SELECT
    p.sku_id,
    p.name,
    p.price_krw AS normal_price_krw,
    pr.discount_krw,
    (p.price_krw - pr.discount_krw) AS current_sale_price_krw
FROM promotions pr
JOIN products p ON p.sku_id = pr.sku_id
WHERE '2026-08-18 12:00:00' BETWEEN pr.starts_at AND pr.ends_at
ORDER BY pr.discount_krw DESC, p.sku_id
LIMIT 50;

